import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.resolve(root, '../ScreenpunkCore/Sources/ScreenpunkCore/AuthoringResources');
const check = process.argv.includes('--check');
const files = [['definitions/authoring-v1.json', 'authoring-v1.json'], ['fixtures/conformance-v1.json','conformance-v1.json'], ['fixtures/conformance-v2.json','conformance-v2.json']];
let drift = false;
function sync(output, value) { if (check) { if (!fs.existsSync(output) || fs.readFileSync(output,'utf8') !== value) { console.error(`Authoring contract drift: ${output}`); drift = true; } } else { fs.mkdirSync(path.dirname(output), {recursive:true}); fs.writeFileSync(output,value); } }
for (const [source, name] of files) sync(path.join(target,name),fs.readFileSync(path.join(root,source),'utf8'));
const definition = fs.readFileSync(path.join(root,'definitions/authoring-v1.json'),'utf8');
sync(path.join(root,'generated/authoring-definition.ts'),'// Generated by scripts/sync-authoring.mjs; edit definitions/authoring-v1.json.\nexport default '+definition.trim()+' as const;\n');
const parsed = JSON.parse(definition);
for (const name of ['Request','Result','Preference','Receipt']) sync(path.join(root,'definitions',name.toLowerCase()+'-v1.schema.json'),JSON.stringify(parsed.schemas[name],null,2)+'\n');

const v2 = fs.readFileSync(path.join(root,'definitions/authoring-v2.json'),'utf8');
sync(path.join(target,'authoring-v2.json'),v2);
sync(path.join(root,'generated/authoring-v2-definition.ts'),'// Generated by scripts/sync-authoring.mjs; edit definitions/authoring-v2.json.\nexport default '+v2.trim()+' as const;\n');
for (const name of ['Request','Result']) sync(path.join(root,'definitions',name.toLowerCase()+'-v2.schema.json'),JSON.stringify(JSON.parse(v2).schemas[name],null,2)+'\n');
if(drift) process.exit(1);
