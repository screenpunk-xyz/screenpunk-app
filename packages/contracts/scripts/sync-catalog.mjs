import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const definition=JSON.parse(fs.readFileSync(path.join(root,'definitions/catalog-v1.json'),'utf8'));
const check=process.argv.includes('--check');let drift=false;
function sync(file,value){const target=path.join(root,file);if(check){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==value){console.error(`Catalog contract drift: ${file}`);drift=true;}}else fs.writeFileSync(target,value);}
sync('generated/catalog-definition.ts','// Generated by scripts/sync-catalog.mjs; edit definitions/catalog-v1.json.\nexport default '+JSON.stringify(definition,null,2)+' as const;\n');
for(const [name,schema] of Object.entries(definition.schemas))sync(`definitions/catalog-${name.toLowerCase()}-v1.schema.json`,JSON.stringify({...schema,$schema:'https://json-schema.org/draft/2020-12/schema',$id:'https://screenpunk.xyz/contracts/catalog-v1/'+name,$defs:definition.schemas},null,2)+'\n');
if(drift)process.exit(1);
